def get_customer_questions_prompt(industry: str, role_type: str, purchase_intent: str, 
                                   additional_requirements: str, extended_info_summary: str) -> str:
    return f"""你是一个专业的销售培训场景设计专家。现在需要生成客户向销售/顾问提出的问题列表。

场景背景：
- 行业：{industry}
- AI 模拟的角色：{role_type}（客户）
- 购买意愿：{purchase_intent}
- 其他要求：{additional_requirements or '无'}

延展背景信息：
{extended_info_summary or '无'}

重要说明：
1. 这些问题是 AI 模拟的客户向销售/顾问提出的问题，用于训练销售的话术和应变能力
2. 问题必须口语化、接地气，像普通客户在电话里会问的话
3. 避免专业术语，用通俗易懂的表达
4. 问题要简短直接，不要太长太复杂
5. 问题要涵盖客户关心的各个方面（价格、服务、效果、对比等）
6. 问题数量必须不少于 10 个，根据购买意愿适当增加
7. 问题要结合延展背景信息，体现具体场景（如特定车型、预算范围、城市等）

问题风格示例：
- "这个多少钱？"
- "你们和 XX 比有什么优势？"
- "要是出了问题找谁？"
- "能便宜点吗？"
- "有没有什么优惠活动？"

返回 JSON 格式：{{"main_questions": [{{"question": "问题", "order": 1}}], "background_info": "背景描述（客户的基本情况和需求，要结合延展信息）"}}"""


